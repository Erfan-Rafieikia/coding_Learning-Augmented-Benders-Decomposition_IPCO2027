print("TEST: Simulating main.py override application")
print("-" * 70)
print()

# Read the actual _apply_runtime_config_override function
PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(PROJECT_ROOT, "src")
main_py_path = os.path.join(SRC_DIR, "main.py")

# Extract and verify the function exists and has the right structure
with open(main_py_path, 'r') as f:
    main_content = f.read()
    
    # Check that all three variables are in the global declaration
    if "global problem_classes_to_instances, method_categories_grid, ml_method_types_grid" in main_content:
        print("✅ main.py has correct global declaration for all 3 variables")
    else:
        print("❌ FAILED: main.py missing global declaration for all variables")
        sys.exit(1)
    
    # Check that method_categories_grid override is applied
    if 'method_categories_grid = override_config.method_categories_grid' in main_content:
        print("✅ main.py applies method_categories_grid from override")
